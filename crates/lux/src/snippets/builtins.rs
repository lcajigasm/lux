fn s(
    name: &str,
    trigger: &str,
    content: &str,
    scope: Option<&str>,
    description: &str,
) -> RawSnippet {
    RawSnippet {
        name: name.to_string(),
        trigger: trigger.to_string(),
        content: content.to_string(),
        scope: scope.map(|s| s.to_string()),
        description: Some(description.to_string()),
    }
}
